        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> Save(IhmReportInfoViewModel model)
        {
            var error = await SaveAll(model);

            var isAjax = string.Equals(
                Request.Headers["X-Requested-With"],
                "XMLHttpRequest",
                StringComparison.OrdinalIgnoreCase
            );

            if (error != null)
            {
                if (isAjax)
                    return BadRequest(error);

                TempData["Error"] = error;
            }
            else
            {
                if (isAjax)
                    return Ok(new { message = "Report saved successfully." });

                TempData["Success"] = "Report saved successfully.";
            }

            return RedirectToAction("Index", new { jobId = model.JobId });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> GeneratePdf(IhmReportInfoViewModel model)
        {
            if (model.JobId <= 0)
            {
                TempData["ErrorMessage"] = "A valid survey job is required to generate the PDF.";
                return RedirectToAction("Ihm", "SurveyJobs");
            }

            try
            {
                _logger.LogInformation("Starting IHM PDF workflow for job {JobId}.", model.JobId);
                NormalizeCollections(model);

                _logger.LogInformation(
                    "Saving report before PDF generation. JobId: {JobId}, Company: {Company}, Client: {Client}, OHS people: {OhsPeople}, Risk rows: {RiskRows}",
                    model.JobId,
                    model.CompanyName,
                    model.ClientName,
                    model.OhsPeople?.Count ?? 0,
                    model.OhsRiskAssessmentRows?.Count ?? 0
                );
                var error = await SaveAll(model);
                if (error != null)
                {
                    _logger.LogWarning(
                        "IHM PDF generation for job {JobId} stopped because saving failed: {Error}",
                        model.JobId,
                        error);
                    if (Request.Headers["X-Requested-With"] == "XMLHttpRequest")
                        return BadRequest(error);

                    TempData["ErrorMessage"] = error;
                    return RedirectToAction(nameof(Index), new { jobId = model.JobId });
                }

                var client = CreateApiClient();

                // Marker images are pre-generated by the API when markers/layouts/images change.
                // PDF generation must not wait for marker image generation.
                _logger.LogInformation(
                    "Skipping synchronous GA marker map generation during PDF workflow. JobId: {JobId}",
                    model.JobId
                );

                // Optional: ask backend to check/queue stale marked images, but do not wait.
                try
                {
                    using var markedImageRequest = new HttpRequestMessage(
                        HttpMethod.Post,
                        $"ihm-survey/jobs/{model.JobId}/marked-images/regenerate"
                    )
                    {
                        Content = new StringContent(
                            "{\"force\":false}",
                            Encoding.UTF8,
                            "application/json"
                        )
                    };

                    using var markedImageResponse = await client.SendAsync(markedImageRequest);

                    _logger.LogInformation(
                        "Marked image pre-generation check queued for job {JobId}. StatusCode={StatusCode}",
                        model.JobId,
                        (int)markedImageResponse.StatusCode
                    );
                }
                catch (Exception ex)
                {
                    _logger.LogWarning(
                        ex,
                        "Unable to queue marked image pre-generation check for job {JobId}. Continuing PDF generation.",
                        model.JobId
                    );
                }

                // Step 2: Generate PDF only after marker map succeeds.
                var path =
                    $"ihm-survey/jobs/{model.JobId}/generate-report";
                var requestUri = new Uri(client.BaseAddress!, path);
                _logger.LogInformation("POST {RequestUri}", requestUri);

                using var request = new HttpRequestMessage(HttpMethod.Post, path)
                {
                    Content = new StringContent("{}", Encoding.UTF8, "application/json")
                };
                using var timeoutCts = new CancellationTokenSource(TimeSpan.FromMinutes(15));
                using var response = await client.SendAsync(request, timeoutCts.Token);

                if (!response.IsSuccessStatusCode)
                {
                    var apiError = await ReadError(response, "PDF generation failed.");
                    _logger.LogError(
                        "IHM PDF API failed for job {JobId}. Status: {StatusCode}. Response: {Response}",
                        model.JobId,
                        (int)response.StatusCode,
                        apiError);
                    if (IsAjaxRequest())
                        return StatusCode((int)response.StatusCode, new { message = apiError });

                    TempData["ErrorMessage"] = apiError;
                    return RedirectToAction(nameof(Index), new { jobId = model.JobId });
                }

                _logger.LogInformation("IHM PDF generation started for job {JobId}.", model.JobId);

                if (Request.Headers["X-Requested-With"] == "XMLHttpRequest")
                {
                    return Json(new
                    {
                        status = "processing",
                        statusUrl = Url.Action(nameof(PdfStatus), new { jobId = model.JobId }),
                        pdfUrl = Url.Action(nameof(ViewPdf), new { jobId = model.JobId })
                    });
                }

                TempData["SuccessMessage"] = "PDF generation started. Please wait and refresh PDF status.";
                return RedirectToAction(nameof(Index), new { jobId = model.JobId });
            }
            catch (TaskCanceledException ex)
            {
                _logger.LogError(ex, "IHM PDF API timed out for job {JobId}.", model.JobId);
                var message = "Report generation is taking too long. Please try again after reducing large images/layouts.";
                if (IsAjaxRequest())
                    return StatusCode(504, new { message });

                TempData["ErrorMessage"] = message;
            }
            catch (HttpRequestException ex)
            {
                _logger.LogError(ex, "Unable to call the IHM PDF API for job {JobId}.", model.JobId);
                var message = $"Unable to connect to the PDF API: {ex.Message}";
                if (IsAjaxRequest())
                    return StatusCode(502, new { message });

                TempData["ErrorMessage"] = message;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Unexpected IHM PDF error for job {JobId}.", model.JobId);
                var message = $"PDF generation failed: {ex.GetBaseException().Message}";
                if (IsAjaxRequest())
                    return StatusCode(500, new { message });

                TempData["ErrorMessage"] = message;
            }

            return RedirectToAction(nameof(Index), new { jobId = model.JobId });
        }

