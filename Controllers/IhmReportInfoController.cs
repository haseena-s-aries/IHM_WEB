        private HttpClient CreateApiClient()
        {
            var client = _clientFactory.CreateClient("ApiClient");
            var jwt = HttpContext.Session.GetString("JWT");
            if (!string.IsNullOrWhiteSpace(jwt))
                client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", jwt);

            return client;
        }

        private static StringContent JsonContent(object value) =>
            new(JsonConvert.SerializeObject(value), Encoding.UTF8, "application/json");

        private bool IsAjaxRequest() =>
            string.Equals(
                Request.Headers["X-Requested-With"],
                "XMLHttpRequest",
                StringComparison.OrdinalIgnoreCase);

        private static async Task<string> ReadError(HttpResponseMessage response, string fallback)
        {
            var message = await response.Content.ReadAsStringAsync();
            if (string.IsNullOrWhiteSpace(message))
                return fallback;

            try
            {
                var values = JsonConvert.DeserializeObject<Dictionary<string, object?>>(message);
                if (values != null)
                {
                    foreach (var key in new[] { "message", "error", "Message", "Error" })
                    {
                        if (values.TryGetValue(key, out var value) && value != null)
                            return value.ToString() ?? fallback;
                    }
                }
            }
            catch
            {
                // Plain-text API errors are returned as-is below.
            }

            return message.Trim().Trim('"');
        }

