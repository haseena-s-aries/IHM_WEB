                    VesselId = job.VesselId,
                    VesselName = vessel?.VesselName ?? job.VesselName,
                    ImoNumber = vessel?.ImoNumber ?? job.ImoNumber,
                    OfficialNumber = vessel?.OfficialNumber,
                    VesselType = vessel?.VesselType,
